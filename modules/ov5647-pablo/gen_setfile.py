#!/usr/bin/env python3
"""Generate is-cis-ov5647-setA.h from the mainline Linux ov5647.c register tables.

usage: gen_setfile.py ov5647.c > is-cis-ov5647-setA.h

Source: torvalds/linux v6.6 drivers/media/i2c/ov5647.c (GPL-2.0). Each {reg, val} pair
becomes a Samsung Pablo tuple (reg, val, 1 byte). A 5 ms I2C_MODE_DELAY is inserted after
the software reset (0x0103 = 0x01), which the mainline driver relies on I2C latency for.
"""
import re
import sys

MODES = [  # order = Pablo mode index = DT modes/modeN
    ('ov5647_640x480_10bpp', '640x480', 'VGA, 2x2 binned + subsampled, RAW10, 60 fps'),
    ('ov5647_2x2binned_10bpp', '1296x972', '2x2 binned full FOV, RAW10, ~46 fps'),
    ('ov5647_1080p30_10bpp', '1920x1080', 'centre crop, RAW10, 30 fps'),
    ('ov5647_2592x1944_10bpp', '2592x1944', 'full resolution, RAW10, 15 fps'),
]

src = open(sys.argv[1]).read()


def table(name):
    m = re.search(r'regval_list\s+%s\[\]\s*=\s*\{(.*?)\n\};' % name, src, re.S)
    if not m:
        raise SystemExit('table %s not found' % name)
    return [(int(a, 16), int(b, 16)) for a, b in re.findall(r'\{\s*(0x[0-9a-fA-F]+)\s*,\s*(0x[0-9a-fA-F]+)\s*\}', m.group(1))]


out = ['/* SPDX-License-Identifier: GPL-2.0 */',
       '/*',
       ' * OV5647 register tables for the Exynos Pablo CIS framework.',
       ' * Generated by modules/ov5647-pablo/gen_setfile.py from mainline Linux v6.6',
       ' * drivers/media/i2c/ov5647.c. Do not edit by hand.',
       ' * Tuple format: register, value, byte count (or I2C_MODE_DELAY, microseconds, 0).',
       ' */',
       '#ifndef IS_CIS_OV5647_SET_A_H',
       '#define IS_CIS_OV5647_SET_A_H',
       '',
       '#include "is-cis.h"',
       '#include "is-cis-ov5647.h"',
       '']

oe = table('sensor_oe_enable_regs')
out.append('/* Output pads on (mainline sensor_oe_enable_regs), then stream-off state so the')
out.append(' * MIPI lanes sit in LP-11 before the CSIS receiver is started. */')
out.append('static const u32 sensor_ov5647_setfile_A_Global[] = {')
for r, v in oe:
    out.append('\t0x%04x, 0x%02x, 0x1,' % (r, v))
out.append('\tOV5647_REG_MIPI_CTRL00, OV5647_MIPI_CTRL00_STREAM_OFF, 0x1,')
out.append('\tOV5647_REG_FRAME_OFF_NUMBER, 0x0f, 0x1,')
out.append('\tOV5647_REG_PAD_OUT, 0x01, 0x1,')
out.append('};')
out.append('')

names = []
for name, size, desc in MODES:
    regs = table(name)
    cname = 'sensor_ov5647_setfile_A_' + size
    names.append(cname)
    out.append('/* %s: %s (%d registers) */' % (size, desc, len(regs)))
    out.append('static const u32 %s[] = {' % cname)
    for r, v in regs:
        out.append('\t0x%04x, 0x%02x, 0x1,' % (r, v))
        if (r, v) == (0x0103, 0x01):
            out.append('\tI2C_MODE_DELAY, 5000, 0x0,')
    out.append('};')
    out.append('')

out.append('static const u32 *sensor_ov5647_setfiles_A[] = {')
out += ['\t%s,' % n for n in names]
out.append('};')
out.append('')
out.append('static const u32 sensor_ov5647_setfile_A_sizes[] = {')
out += ['\tARRAY_SIZE(%s),' % n for n in names]
out.append('};')
out.append('')
out.append('#endif')
print('\n'.join(out))
